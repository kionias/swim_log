type SeedRow = [string, number];

const createWorkout = (date: string, classId: string, quote: string, rows: SeedRow[]): WorkoutWithDetails => {
  const id = `w-${date}`;
  const sets: WorkoutSet[] = rows.map(([description, distance], index) => ({
    id: `s-${date}-${index + 1}`,
    workout_id: id,
    sequence: index + 1,
    distance,
    description,
  }));

  return {
    id,
    class_id: classId,
    pool_id: 'pool-1',
    workout_date: date,
    duration_minutes: 60,
    total_distance: sets.reduce((sum, set) => sum + set.distance, 0),
    memo: '',
    quote,
    pool: INITIAL_POOLS[0],
    class: INITIAL_CLASSES.find((item) => item.id === classId),
    sets,
  };
};

